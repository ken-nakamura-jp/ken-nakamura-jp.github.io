"""Build the site's render-blocking font stylesheet; see README for regeneration."""

import base64
import io
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
# Basic Latin, Latin-1 accents and punctuation used by the English site.
RANGES = [(0x20, 0xFF), (0x2000, 0x206F)]
CODEPOINTS = {codepoint for start, end in RANGES for codepoint in range(start, end + 1)}
FAMILY = "Ken Profile Sans"  # Rename the subset to respect Source's reserved name.
VARIANTS = [("Regular", "normal", "400"), ("Semibold", "normal", "600 900"), ("RegularIt", "italic", "400")]

blocks = [
    "/* Generated by bin/build_profile_fonts.py; do not edit.\n"
    " * Source Sans 3 subset, renamed Ken Profile Sans.\n"
    " * License: /assets/fonts/source-sans-3/LICENSE.txt\n"
    " * Embedded fonts arrive with this blocking stylesheet, avoiding a fallback-font flash.\n"
    " */"
]
for variant, style, weight in VARIANTS:
    font = TTFont(ROOT / "bin/fonts/source-sans-3" / f"SourceSans3-{variant}.woff", recalcTimestamp=False)
    options = subset.Options()
    options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14, 16, 17]
    options.name_legacy = True
    options.name_languages = [0x409]
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=CODEPOINTS)
    subsetter.subset(font)
    names = font["name"]
    for record in names.names:
        replacements = {
            1: FAMILY,
            3: f"{FAMILY}-{variant}",
            4: f"{FAMILY} {variant}",
            6: f"KenProfileSans-{variant}",
            16: FAMILY,
        }
        if record.nameID in replacements:
            record.string = replacements[record.nameID].encode(record.getEncoding())
    # CFF names are separate from the OpenType naming table.
    if "CFF " in font:
        cff = font["CFF "].cff
        cff.fontNames = [f"KenProfileSans-{variant}"]
        cff.topDictIndex[0].FamilyName = FAMILY
        cff.topDictIndex[0].FullName = f"{FAMILY} {variant}"
    font.flavor = "woff2"
    output = io.BytesIO()
    font.save(output)
    encoded = base64.b64encode(output.getvalue()).decode("ascii")
    blocks.append(
        f'@font-face {{\n  font-family: "{FAMILY}";\n'
        f'  src: url("data:font/woff2;base64,{encoded}") format("woff2");\n'
        f"  font-style: {style};\n  font-weight: {weight};\n  font-display: block;\n}}"
    )
    print(f"{variant}: {len(output.getvalue()):,} bytes")
(ROOT / "assets/css/profile-fonts.css").write_text("\n".join(blocks) + "\n")
